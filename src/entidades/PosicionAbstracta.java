package entidades;

public abstract class PosicionAbstracta  {
	//Atributos de instancia
	protected int x;
	protected int y;
	protected int height;
	protected int width;
	
	//Metodos
	public int getX() {
		return x;
	}
	
	public int getY() {
		return y;
	}
	
	public int getHeight() {
		return height;
	}
	
	public int getWidth(){
		return width;
	}
}
